"""
Agent-3: Configuration Proposal Tool for VERITAS.

Inspects dataset metadata and proposes safe, context-appropriate configurations
for fairness and anomaly scanning before the human approval gate:
  - proposed_protected_attributes: demographic columns suitable for parity analysis
  - proposed_min_group_size: threshold to prevent small-group statistical instability
  - proxy_feature_warnings: features that may act as proxies for protected classes
  - significance_level_recommendation: literature justification (text only, human sets number)

Determinism & Human-in-the-Loop boundary:
  Agent-3 ONLY PROPOSES. The human auditor confirms, modifies, or rejects all
  parameters at the approval gate before any audit calculations execute.
  Raw record rows are NEVER sent to the LLM; only column summary statistics.
"""
from __future__ import annotations

import json
import logging
import math
import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Set

import pandas as pd

logger = logging.getLogger(__name__)

PROXY_KEYWORDS: Set[str] = {
    "zip", "postal", "area_code", "neighborhood", "city",
    "surname", "name", "school", "university", "college",
    "club", "association", "sorority", "fraternity"
}

KNOWN_DEMOGRAPHIC_CANDIDATES: Set[str] = {
    "sex", "gender", "race", "ethnicity", "age", "age_group",
    "marital_status", "nationality", "religion", "disability", "veteran_status"
}


@dataclass
class ConfigProposal:
    """Proposal generated by Agent-3 for human review."""
    proposed_protected_attributes: List[str]
    proposed_min_group_size: int
    proxy_feature_warnings: List[str]
    significance_level_recommendation: str
    attribute_rationales: Dict[str, str]
    group_size_rationale: str
    source: str = "deterministic"          # "deterministic" | "llm"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "proposed_protected_attributes": self.proposed_protected_attributes,
            "proposed_min_group_size": self.proposed_min_group_size,
            "proxy_feature_warnings": self.proxy_feature_warnings,
            "significance_level_recommendation": self.significance_level_recommendation,
            "attribute_rationales": self.attribute_rationales,
            "group_size_rationale": self.group_size_rationale,
            "source": self.source,
        }


def _profile_dataset_metadata(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Extract privacy-preserving dataset metadata."""
    if not records:
        return {"row_count": 0, "columns": {}}

    df = pd.DataFrame(records)
    row_count = len(df)
    columns_meta = {}

    for col in df.columns:
        series = df[col]
        # Handle dict column (e.g. protected_attributes dict in normalized records)
        if series.dropna().empty:
            continue
        first_val = series.dropna().iloc[0]
        if isinstance(first_val, dict):
            # Flatten sub-keys
            for sub_k in first_val.keys():
                sub_series = series.apply(lambda d: d.get(sub_k) if isinstance(d, dict) else None)
                val_counts = sub_series.value_counts().head(5).to_dict()
                columns_meta[f"protected_attributes.{sub_k}"] = {
                    "cardinality": int(sub_series.nunique()),
                    "top_values": {str(k): int(v) for k, v in val_counts.items()},
                    "dtype": "categorical",
                }
            continue

        val_counts = series.value_counts().head(5).to_dict()
        columns_meta[str(col)] = {
            "cardinality": int(series.nunique()),
            "top_values": {str(k): int(v) for k, v in val_counts.items()},
            "dtype": str(series.dtype),
        }

    return {
        "row_count": row_count,
        "columns": columns_meta,
    }


def propose_config_deterministic(
    records: List[Dict[str, Any]],
    current_defaults: Optional[Dict[str, Any]] = None,
) -> ConfigProposal:
    """
    Generate deterministic config proposal based on statistical dataset properties.
    Never calls an LLM.
    """
    row_count = len(records)
    if row_count == 0:
        return ConfigProposal(
            proposed_protected_attributes=[],
            proposed_min_group_size=30,
            proxy_feature_warnings=[],
            significance_level_recommendation="Default α=0.05 is standard in literature.",
            attribute_rationales={},
            group_size_rationale="Default 30 records per group for empty dataset.",
            source="deterministic",
        )

    # 1. Inspect protected attributes
    # Check both direct columns and records[i]["protected_attributes"]
    detected_attributes: Set[str] = set()
    sample_record = records[0]
    if "protected_attributes" in sample_record and isinstance(sample_record["protected_attributes"], dict):
        detected_attributes.update(sample_record["protected_attributes"].keys())

    df = pd.DataFrame(records)
    for col in df.columns:
        c_low = str(col).lower()
        if any(cand in c_low for cand in KNOWN_DEMOGRAPHIC_CANDIDATES):
            detected_attributes.add(str(col))

    proposed_attrs = sorted(detected_attributes)
    attr_rationales = {
        attr: f"Identified as demographic/protected class candidate with distinct groups in data."
        for attr in proposed_attrs
    }

    # 2. Inspect potential proxy features
    proxy_warnings = []
    for col in df.columns:
        c_low = str(col).lower()
        if any(kw in c_low for kw in PROXY_KEYWORDS) and col not in proposed_attrs:
            proxy_warnings.append(
                f"Feature '{col}' may act as a geographic or socioeconomic proxy for protected classes (Mehrabi et al., 2021)."
            )

    # 3. Compute recommended min_group_size
    # Rule of thumb: at least 30 records for Central Limit Theorem, or ~1-2% of dataset, capped at 100
    if row_count < 100:
        recommended_group_size = max(5, int(row_count * 0.1))
        group_rationale = (
            f"Dataset is small ({row_count} rows). Group size threshold lowered to {recommended_group_size} "
            "to prevent suppressing all groups, though results will carry wide confidence intervals."
        )
    else:
        # Standard: 30 to 50
        recommended_group_size = min(100, max(30, int(row_count * 0.005)))
        group_rationale = (
            f"Recommended {recommended_group_size} records per group based on Central Limit Theorem "
            f"for reliable variance estimation on {row_count} total records."
        )

    sig_rec = (
        "Significance level α=0.05 recommended following standard hypothesis testing convention "
        "(EEOC Uniform Guidelines; NIST AI RMF MAP 1.1). Human reviewer must confirm."
    )

    return ConfigProposal(
        proposed_protected_attributes=proposed_attrs,
        proposed_min_group_size=recommended_group_size,
        proxy_feature_warnings=proxy_warnings,
        significance_level_recommendation=sig_rec,
        attribute_rationales=attr_rationales,
        group_size_rationale=group_rationale,
        source="deterministic",
    )


def propose_config(
    records: List[Dict[str, Any]],
    llm_client: Optional[Any] = None,
    current_defaults: Optional[Dict[str, Any]] = None,
) -> ConfigProposal:
    """
    Main entrypoint for Agent-3 Config Proposal.
    """
    det_proposal = propose_config_deterministic(records, current_defaults)
    if llm_client is None:
        return det_proposal

    # If LLM is available, enrich proposal rationales using privacy-safe metadata only
    metadata = _profile_dataset_metadata(records)
    prompt = (
        "You are an AI governance auditor reviewing a dataset's metadata for fairness audit configuration.\n"
        "Given the summary metadata below, propose the protected attributes and minimum group size.\n\n"
        f"Dataset Metadata Summary:\n{json.dumps(metadata, indent=2)}\n\n"
        f"Deterministic Baseline Proposal:\n{json.dumps(det_proposal.to_dict(), indent=2)}\n\n"
        "Instructions:\n"
        "1. Identify which attributes represent protected demographic classes.\n"
        "2. Warn if any feature might act as a proxy.\n"
        "3. Provide a clear, defensible rationale citing statistical principles (e.g. sample size stability).\n"
        "Respond ONLY with a valid JSON object matching:\n"
        "{\n"
        '  "proposed_protected_attributes": ["attr1", ...],\n'
        '  "proposed_min_group_size": 30,\n'
        '  "proxy_feature_warnings": ["..."],\n'
        '  "attribute_rationales": {"attr1": "..."},\n'
        '  "group_size_rationale": "...",\n'
        '  "significance_level_recommendation": "..."\n'
        "}"
    )

    try:
        response = llm_client.invoke(prompt)
        text = response.content if hasattr(response, "content") else str(response)
        json_match = re.search(r"\{.*\}", text, re.DOTALL)
        if not json_match:
            return det_proposal
        data = json.loads(json_match.group(0))

        # Validate that proposed attributes exist in data
        df = pd.DataFrame(records)
        all_cols = set(df.columns)
        if records and "protected_attributes" in records[0] and isinstance(records[0]["protected_attributes"], dict):
            all_cols.update(records[0]["protected_attributes"].keys())

        valid_attrs = [
            a for a in data.get("proposed_protected_attributes", det_proposal.proposed_protected_attributes)
            if a in all_cols
        ]
        if not valid_attrs:
            valid_attrs = det_proposal.proposed_protected_attributes

        min_group = int(data.get("proposed_min_group_size", det_proposal.proposed_min_group_size))
        # Clamp min_group to reasonable bounds
        min_group = max(5, min(min_group, max(30, len(records) // 2)))

        return ConfigProposal(
            proposed_protected_attributes=valid_attrs,
            proposed_min_group_size=min_group,
            proxy_feature_warnings=data.get("proxy_feature_warnings", det_proposal.proxy_feature_warnings),
            significance_level_recommendation=data.get(
                "significance_level_recommendation", det_proposal.significance_level_recommendation
            ),
            attribute_rationales=data.get("attribute_rationales", det_proposal.attribute_rationales),
            group_size_rationale=data.get("group_size_rationale", det_proposal.group_size_rationale),
            source="llm",
        )
    except Exception as exc:
        logger.warning("LLM config proposal failed: %s. Falling back to deterministic proposal.", exc)
        return det_proposal
